suppressMessages(library(multigrain))
set.seed(5)
S <- matrix(0.4, 5, 5); diag(S) <- 1
P <- simulate_pvalues(c(0.9, 0.8, 0.8, 0.7, 0.6), corr_matrix = S, nsim = 3000)
fs <- family_spec(list(primary = 1, secondary = 2:4, other = 5))
gain <- trial_success(2 * r1 + (r2 && r3 && r4) + 0.5 * r5, verbose = "silent")
msg <- function(expr) tryCatch({ force(expr); "ACCEPTED" }, error = function(e) gsub("\n", " ", conditionMessage(e)))
cat("constraint with 5 nodes and 3 families :", msg(graph_optimise(P, graph_constraint_free(5), gain, families = fs, verbose = "silent")), "\n")
fit <- graph_optimise(P, graph_constraint_free(3), gain, families = fs, verbose = "silent")
cat("names of the optimised weights         :", names(fit$hyp_weight), "\n")
cat("family names in the specification       :", names(fs$members), "\n")
cat("rownames of the transition matrix       :", rownames(fit$trans_matrix), "\n")
cat("names of local_power                    :", names(fit$power$local_power), "\n")
cat("names of family_power                   :", names(fit$power$family_power), "\n")
g <- ggplot2::ggplot_build(plot(fit))
labs <- unique(unlist(lapply(g$data, function(d) if ("label" %in% names(d)) as.character(d$label))))
cat("labels drawn by plot()                  :", head(labs, 12), "\n")
cat("summary():\n"); print(summary(fit))
